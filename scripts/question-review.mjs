#!/usr/bin/env node
// Writes docs/question-review.md: every question in the P1.5 banks with its answer, for human review.
// Usage: npm run questions:review
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSeed } from './seed-data.mjs';

export const REVIEW_SLUGS = ['javascript', 'html-css', 'java', 'powerpoint', 'canva', 'teamwork', 'public-speaking'];
const UI_DEPENDENT = new Set(['powerpoint', 'canva']);
const LEVEL = { 1: 'Easy', 2: 'Medium', 3: 'Hard' };

/** Markdown would render <h1> etc. as real HTML outside code blocks. */
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');

/** Question text first, then any code after the first blank line in a fenced block. */
function renderBody(body) {
  const split = body.indexOf('\n\n');
  if (split === -1 || !/\n|[;{}<>]/.test(body.slice(split + 2))) return esc(body);
  return `${esc(body.slice(0, split))}\n\n\`\`\`\n${body.slice(split + 2)}\n\`\`\``;
}

export function renderReview(seed) {
  const skills = REVIEW_SLUGS.map((slug) => seed.skills.find((s) => s.slug === slug)).filter(Boolean);
  const total = skills.reduce((n, s) => n + s.questions.length, 0);
  const out = [
    '# Question bank review (P1.5)',
    '',
    '<!-- Generated by scripts/question-review.mjs from supabase/seed. Do not edit by hand: fix the seed JSON and re-run `npm run questions:review`. -->',
    '',
    `${total} new questions across ${skills.length} skills. Each test picks 12 at random: 4 easy, 5 medium, 3 hard. Options are shuffled for every attempt, so the letter shown here is only the stored order.`,
    '',
    '**For reviewers, check each question for:**',
    '- the marked answer is the only correct one;',
    '- the explanation is accurate;',
    '- the wording is clear for a final-year student reading on a phone;',
    '- the difficulty tag is right.',
    '',
    'Tick the box when a question is approved. To report a problem, quote the question key (for example `js-m04`).',
    '',
    '## Contents',
    '',
    ...skills.map((s) => `- [${s.name}](#${s.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}) (${s.questions.length})`),
    '',
  ];
  for (const s of skills) {
    out.push(`## ${s.name}`, '');
    out.push(`Slug \`${s.slug}\` · category ${s.category} · file \`supabase/seed/questions/${s.file}\``, '');
    if (UI_DEPENDENT.has(s.slug)) {
      out.push('> These questions refer to menus and shortcuts. Check them against the current version of the app before release.', '');
    }
    for (const q of s.questions) {
      out.push(`### \`${q.key}\` · ${LEVEL[q.difficulty]} · ${q.type}`, '');
      out.push(renderBody(q.body), '');
      q.options.forEach((o, i) => {
        const letter = 'ABCD'[i];
        out.push(i === q.correct ? `- **${letter}. ${esc(o)}** ✅` : `- ${letter}. ${esc(o)}`);
      });
      out.push('', `*Why:* ${esc(q.explanation ?? '(missing)')}`, '', '- [ ] Approved', '');
    }
  }
  return out.join('\n');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  mkdirSync(path.join(root, 'docs'), { recursive: true });
  writeFileSync(path.join(root, 'docs', 'question-review.md'), renderReview(loadSeed()));
  console.log('wrote docs/question-review.md');
}
